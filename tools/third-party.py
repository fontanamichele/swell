"""Writes the list of Rust dependencies and their licences (core/Cargo.lock) as Markdown.

usage: tools/third-party.py > docs/third-party-rust.md
"""

import json
import os
import subprocess
import sys

here = os.path.dirname(os.path.abspath(__file__))
core = os.path.join(here, "..", "core")
meta = json.loads(
    subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked"],
        cwd=core,
        capture_output=True,
        text=True,
        check=True,
    ).stdout
)
workspace = set(meta["workspace_members"])
rows = sorted(
    (
        p["name"],
        p["version"],
        p.get("license") or "see the crate",
        p.get("repository") or "",
    )
    for p in meta["packages"]
    if p["id"] not in workspace
)
print("# Rust dependencies of the Swell core\n")
print(
    "Generated by `tools/third-party.py` from `core/Cargo.lock`. Each crate is under the"
)
print("licence shown; where it offers a choice (`OR`), Swell uses it under either.\n")
print("| Crate | Version | Licence | Source |")
print("| --- | --- | --- | --- |")
for name, version, lic, repo in rows:
    print(f"| {name} | {version} | {lic} | {repo} |")
print(f"\n{len(rows)} crates.", file=sys.stdout)
